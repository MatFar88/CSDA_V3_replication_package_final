function paths = ecb_trkm_path_lock_v1(package_root)
%ECB_TRKM_PATH_LOCK_V1 Put bundled production sources first and verify them.
if nargin<1 || strlength(string(package_root))==0
    package_root = fileparts(mfilename('fullpath'));
end
package_root = char(string(package_root));
vendor = fullfile(package_root,'vendor');
assert(isfolder(vendor),'Bundled vendor directory not found: %s',vendor);
addpath(genpath(vendor),'-begin');
rehash path;
req = ["regularized_trimmed_fit_corrected_v1", ...
       "make_robust_initialization_v1", ...
       "adjusted_rand_index_v1", ...
       "compute_external_alpha_fit_stats_v1", ...
       "compute_operational_candidate_row_unseen_v1", ...
       "run_hd_multistart_top_v1", ...
       "select_robust_view_v3", ...
       "score_candidates_robust_views_v3", ...
       "build_robust_views_v3", ...
       "select_rg_frozen_v1"];
paths = strings(numel(req),1);
canon = string(vendor);
for k=1:numel(req)
    f = string(which(char(req(k))));
    assert(strlength(f)>0,'Missing required function: %s',req(k));
    assert(startsWith(f,canon,'IgnoreCase',true), ...
        'PATH LOCK FAIL: %s resolves to %s',req(k),f);
    paths(k)=f;
end
end
